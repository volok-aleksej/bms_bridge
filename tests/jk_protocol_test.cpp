// ---- JkFrameAssembler ----------------------------------------------------

TEST(JkFrameAssembler, IgnoresAtPings) {
    JkFrameAssembler a;
    const uint8_t pings[] = {0x41, 0x54, 0x0D, 0x0A, 0x41, 0x54, 0x0D, 0x0A};
    a.push_chunk(pings, sizeof(pings));
    EXPECT_FALSE(a.take_complete_frame().has_value());
}

TEST(JkFrameAssembler, AssemblesContiguousSniffedFrame) {
    JkFrameAssembler a;
    a.push_chunk(kSniffedCellInfoFrame.data(), kSniffedCellInfoFrame.size());

    auto got = a.take_complete_frame();
    ASSERT_TRUE(got.has_value());
    EXPECT_EQ(std::vector<uint8_t>(kSniffedCellInfoFrame.begin(),
                                   kSniffedCellInfoFrame.end()),
              *got);
    EXPECT_FALSE(a.take_complete_frame().has_value());
}

TEST(JkFrameAssembler, AssemblesSniffedFrameChunkedWithNoise) {
    JkFrameAssembler a;

    // Leading AT-pings (idle traffic from the BLE chip).
    const uint8_t leading[] = {0x41, 0x54, 0x0D, 0x0A};
    a.push_chunk(leading, sizeof(leading));

    // Feed the 300-byte frame in 20-byte BLE-MTU-sized chunks like real notify.
    constexpr size_t mtu = 20;
    for (size_t i = 0; i < kSniffedCellInfoFrame.size(); i += mtu) {
        const size_t n = std::min(mtu, kSniffedCellInfoFrame.size() - i);
        a.push_chunk(kSniffedCellInfoFrame.data() + i, n);
    }

    const uint8_t trailing[] = {0x41, 0x54, 0x0D, 0x0A};
    a.push_chunk(trailing, sizeof(trailing));

    auto got = a.take_complete_frame();
    ASSERT_TRUE(got.has_value());
    EXPECT_EQ(std::vector<uint8_t>(kSniffedCellInfoFrame.begin(),
                                   kSniffedCellInfoFrame.end()),
              *got);
}

TEST(JkFrameAssembler, DropsFrameWithBadCrc) {
    auto frame = kSniffedCellInfoFrame;
    frame.back() ^= 0xFF;  // corrupt CRC

    JkFrameAssembler a;
    a.push_chunk(frame.data(), frame.size());
    EXPECT_FALSE(a.take_complete_frame().has_value());
}

TEST(JkFrameAssembler, RecoversAfterMisalignedMagicPrefix) {
    JkFrameAssembler a;

    // 55 AA EB <not-90> — looks like start of magic but isn't; must be discarded
    // without breaking subsequent valid-frame assembly.
    const uint8_t garbage[] = {0x55, 0xAA, 0xEB, 0x91};
    a.push_chunk(garbage, sizeof(garbage));
    a.push_chunk(kSniffedCellInfoFrame.data(), kSniffedCellInfoFrame.size());

    auto got = a.take_complete_frame();
    ASSERT_TRUE(got.has_value());
    EXPECT_EQ(std::vector<uint8_t>(kSniffedCellInfoFrame.begin(),
                                   kSniffedCellInfoFrame.end()),
              *got);
}
