    EXPECT_EQ(cells.voltages_mv[0],  3289);
    EXPECT_EQ(cells.voltages_mv[1],  3290);
    EXPECT_EQ(cells.voltages_mv[2],  3290);
    EXPECT_EQ(cells.voltages_mv[3],  3296);
    EXPECT_EQ(cells.voltages_mv[4],  3296);
    EXPECT_EQ(cells.voltages_mv[5],  3294);
    EXPECT_EQ(cells.voltages_mv[6],  3299);
    EXPECT_EQ(cells.voltages_mv[7],  3292);
    EXPECT_EQ(cells.voltages_mv[8],  3272);
    EXPECT_EQ(cells.voltages_mv[9],  3288);
    EXPECT_EQ(cells.voltages_mv[10], 3288);
    EXPECT_EQ(cells.voltages_mv[11], 3296);
    EXPECT_EQ(cells.voltages_mv[12], 3296);
    EXPECT_EQ(cells.voltages_mv[13], 3292);
    EXPECT_EQ(cells.voltages_mv[14], 3295);
    EXPECT_EQ(cells.voltages_mv[15], 3292);

    EXPECT_EQ(cells.average_voltage_mv,  3292);
    EXPECT_EQ(cells.voltage_diff_mv,     13);
    EXPECT_EQ(cells.max_voltage_cell_idx, 2);  // BMS reports 1-based '3' → 0-based 2
    EXPECT_EQ(cells.min_voltage_cell_idx, 7);  // BMS reports 1-based '8' → 0-based 7

    ASSERT_EQ(cells.resistance_uohm.size(), 16u);
    EXPECT_EQ(cells.resistance_uohm[0],  158);
    EXPECT_EQ(cells.resistance_uohm[1],  159);
    EXPECT_EQ(cells.resistance_uohm[7],  162);
    EXPECT_EQ(cells.resistance_uohm[15], 161);
